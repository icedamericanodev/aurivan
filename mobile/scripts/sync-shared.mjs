#!/usr/bin/env node
/**
 * sync-shared.mjs: copies the board's pure text rules from the app to the
 * Edge Functions, so the phone and the server always give the same answer
 * (Uplift Phase 8, guard G8; spec PHASE6_8.md §1.6).
 *
 *   node scripts/sync-shared.mjs          write the copies
 *   node scripts/sync-shared.mjs --check  fail (exit 1) if a copy differs
 *
 * WHAT IT DOES (plain English):
 *   mobile/src/engine/leakGuard.ts and moderation.ts are the ONLY source.
 *   Each is copied to supabase/functions/_shared/ with a short "generated"
 *   header, and with its relative imports given the `.ts` ending Deno needs
 *   (`from './moderation'` becomes `from './moderation.ts'`). Nothing else
 *   changes, so the two run the very same code.
 *
 * Edit the engine file, then run this. CI runs `--check` (mobile.yml and
 * supabase.yml), and a Jest test runs it too.
 *
 * No third-party packages: only Node's built-in fs/path modules.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const MOBILE = path.resolve(HERE, '..');
const REPO = path.resolve(MOBILE, '..');
const FROM = path.join(MOBILE, 'src', 'engine');
const TO = path.join(REPO, 'supabase', 'functions', '_shared');

/** The engine files the server shares. Each may import only another one of these. */
export const SHARED = ['moderation', 'leakGuard'];

/** The server copy of one engine file's text. */
export function serverCopy(name, source) {
  const header = [
    `// GENERATED by mobile/scripts/sync-shared.mjs from mobile/src/engine/${name}.ts. Do not edit this copy:`,
    '// change the engine file, then run `node mobile/scripts/sync-shared.mjs` (guard G8 checks they match).',
    '// deno-fmt-ignore-file',
    '',
  ].join('\n');
  const body = source.replace(/(from\s+'\.\/)([A-Za-z]+)(')/g, (whole, a, mod, b) => {
    if (!SHARED.includes(mod)) throw new Error(`${name}.ts imports ./${mod}, which isn't shared with the server`);
    return `${a}${mod}.ts${b}`;
  });
  if (/from\s+'\.\.\//.test(body)) throw new Error(`${name}.ts imports from outside src/engine; the server copy can't`);
  return header + body;
}

function main() {
  const check = process.argv.includes('--check');
  let bad = 0;
  for (const name of SHARED) {
    const want = serverCopy(name, fs.readFileSync(path.join(FROM, `${name}.ts`), 'utf8'));
    const target = path.join(TO, `${name}.ts`);
    const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (have === want) continue;
    if (check) {
      console.error(`✗ supabase/functions/_shared/${name}.ts differs from mobile/src/engine/${name}.ts: run node mobile/scripts/sync-shared.mjs`);
      bad++;
    } else {
      fs.writeFileSync(target, want);
      console.log(`✓ wrote supabase/functions/_shared/${name}.ts`);
    }
  }
  if (check) console.log(bad ? `sync-shared: ${bad} copy(ies) out of date` : `sync-shared: ${SHARED.length} shared file(s) match`);
  process.exit(bad ? 1 : 0);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

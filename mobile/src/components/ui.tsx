// ── Chip: selectable filter (spec §6) ─────────────────────────────────
// Selected = ink fill + bg label + leading ✓ (shape AND colour, never green).
export function Chip({
  label,
  selected,
  onPress,
  accessibilityLabel,
  accessibilityHint,
  disabled,
  checkbox,
}: {
  label: string;
  selected: boolean;
  onPress: () => void;
  /** Spoken name when the visible label is short (e.g. "Remind on Monday" for "Mon"). */
  accessibilityLabel?: string;
  accessibilityHint?: string;
  disabled?: boolean;
  /** One of several independent on/off choices (e.g. reminder days): spoken as checkbox, checked / not checked. */
  checkbox?: boolean;
}) {
  const { c } = useTheme();
  const press = usePressScale({ tint: c.soft, tintRadius: radius.pill });
  // The label and ✓ swap colour at the fill's half-way point (as StateLayer
  // `step` does for a badge): flipping at the tap would put paper-coloured
  // text on a still-transparent fill for a few frames.
  const half = useSharedValue(selected ? 1 : 0);
  useEffect(() => {
    half.set(tween(selected ? 1 : 0, 'select'));
  }, [selected, half]);
  const labelInk = useAnimatedStyle(() => ({ color: half.value >= 0.5 ? c.bg : c.ink }));
  const markShown = useAnimatedStyle(() => ({ opacity: half.value >= 0.5 ? 1 : 0 }));
  return (
    <AnimatedPressable
      accessibilityRole={checkbox ? 'checkbox' : 'button'}
      accessibilityState={{ ...(checkbox ? { checked: selected } : { selected }), ...(disabled ? { disabled } : {}) }}
      disabled={disabled}
      accessibilityHint={accessibilityHint}
      accessibilityLabel={accessibilityLabel ?? label} // the ✓ is visual; the state is spoken
      onPress={onPress}
      hitSlop={4} // 40pt chip + 4pt each side = 48pt touch target
      onPressIn={press.onPressIn}
      onPressOut={press.onPressOut}
      style={[styles.chip, { borderColor: selected ? c.ink : c.control }, press.style]}
    >
      {press.layer}
      {/* The ink fill cross-fades in (120 ms), covering the outline too. */}
      <StateLayer on={selected} style={[styles.chipFill, { backgroundColor: c.ink }]} />
      {/* In a View, so the mark always draws above the fill layer (web paints a bare SVG under it). */}
      {selected && (
        <Animated.View style={markShown}>
          <Check size={14} color={c.bg} strokeWidth={2.5} />
        </Animated.View>
      )}
      <Animated.Text maxFontSizeMultiplier={2} style={[styles.chipLabel, labelInk]}>{label}</Animated.Text>
    </AnimatedPressable>
  );
}

// ── Toggle: an on/off switch in our colours ──────────────────────────
// Wraps the platform Switch so its thumb never falls back to a stock
// teal/blue. On the web build the "on" thumb needs `activeThumbColor`.
export function Toggle({
  value,
  onValueChange,
  disabled,
  accessibilityLabel,
  ref,
}: {
  ref?: Ref<Switch>;
  value: boolean;
  onValueChange: (v: boolean) => void;
  disabled?: boolean;
  accessibilityLabel: string;
}) {
  const { c, isDark } = useTheme();
  const webOnly = Platform.OS === 'web' ? ({ activeThumbColor: c.onBtn } as object) : {};
  // Dark mode, off: the dark `onBtn` thumb sank into the grey track, so it takes
  // the light secondary ink instead (UX review O6). On, it stays `onBtn` on `btn`.
  const offThumb = isDark ? c.ink2 : c.onBtn;
  return (
    <Switch
      ref={ref}
      accessibilityLabel={accessibilityLabel}
      value={value}
      disabled={disabled}
      onValueChange={onValueChange}
      thumbColor={value ? c.onBtn : offThumb}
      trackColor={{ true: c.btn, false: c.muted }}
      ios_backgroundColor={c.muted}
      {...webOnly}
    />
  );
}


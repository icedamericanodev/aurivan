// ── IconButton: a 48pt round button holding one icon ──────────────────
// For header actions (Settings gear, "How it scores"). The icon is visual;
// `label` is what a screen reader says. 48pt meets the 44pt minimum with room.
export function IconButton({
  label,
  onPress,
  icon,
  hint,
  selected,
  expanded,
  disabled,
}: {
  label: string;
  onPress: () => void;
  /** Draw the icon in the colour given (ink, or muted when disabled). */
  icon: (color: string) => ReactNode;
  hint?: string;
  /** For a toggle (on/off). */
  selected?: boolean;
  /** For a button that shows or hides a panel (e.g. "How scoring works"): spoken as expanded / collapsed. */
  expanded?: boolean;
  disabled?: boolean;
}) {
  const { c } = useTheme();
  const state = {
    ...(selected === undefined ? {} : { selected }),
    ...(expanded === undefined ? {} : { expanded }),
    ...(disabled ? { disabled } : {}),
  };
  // Pressed: a soft circle grows in behind the icon (.9 → 1) and fades.
  const press = usePressScale({ scale: 1, tint: c.soft, tintRadius: 24, tintFrom: 0.9 });
  return (
    <AnimatedPressable
      accessibilityRole="button"
      accessibilityLabel={label}
      accessibilityHint={hint}
      accessibilityState={Object.keys(state).length ? state : undefined}
      onPress={onPress}
      disabled={disabled}
      onPressIn={press.onPressIn}
      onPressOut={press.onPressOut}
      style={[styles.iconButton, press.style]}
    >
      {press.layer}
      {icon(disabled ? c.muted : c.ink)}
    </AnimatedPressable>
  );
}

// ── Stepper: − value + for small numbers (the reminder time) ─────────
// No date-picker dependency: two of these make a calm hour/minute picker.
// Touch: two 48pt buttons. Screen readers: ONE adjustable control (swipe
// up or down on iOS; the increment/decrement actions on Android) that
// speaks its name and value; the inner buttons are hidden from them, so
// Android also has a single stop.
export function Stepper({
  label,
  value,
  spoken,
  onDec,
  onInc,
  disabled,
  spokenLabel,
  dir: given,
}: {
  /**
   * Which way the value last moved (+1 later, -1 earlier), from the change
   * itself: the hour moves when the minutes wrap past :00, and must roll the
   * way time moved, not the way the hour was last pressed.
   */
  dir?: 1 | -1;
  /** While true (e.g. a reminder change is being saved), taps are ignored. */
  disabled?: boolean;
  /** "Hour" / "Minutes": the caption, and the buttons' names ("Hour later"). */
  label: string;
  /** What a screen reader calls the control, e.g. "Reminder hour" (defaults to `label`). */
  spokenLabel?: string;
  value: string;
  /** What a screen reader says for the value, e.g. "7 PM". */
  spoken?: string;
  onDec: () => void;
  onInc: () => void;
}) {
  const { c } = useTheme();
  // Mobile 1.9: the value rolls one step the way it moved (160 ms; up for
  // later, down for earlier), so the change is seen, not just swapped. A wrap
  // (12 → 1, 45 → 00) is still one step. Nothing moves on open.
  const [pressed, setDir] = useState<1 | -1>(1);
  const dir = given ?? pressed;
  const [shown, setShown] = useState({ value, from: value, run: 0 });
  if (shown.value !== value) setShown((x) => ({ value, from: x.value, run: x.run + 1 }));
  const dec = () => {
    setDir(-1);
    onDec();
  };
  const inc = () => {
    setDir(1);
    onInc();
  };
  return (
    <View
      accessible
      accessibilityRole="adjustable"
      accessibilityLabel={spokenLabel ?? label}
      accessibilityValue={{ text: spoken ?? value }}
      accessibilityActions={[{ name: 'increment' }, { name: 'decrement' }]}
      accessibilityState={disabled ? { disabled } : undefined}
      onAccessibilityAction={(e) => {
        if (disabled) return;
        if (e.nativeEvent.actionName === 'increment') inc();
        else if (e.nativeEvent.actionName === 'decrement') dec();
      }}
      style={{ alignItems: 'center' }}
    >
      <T v="caption">{label}</T>
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: space.xs }} importantForAccessibility="no-hide-descendants" accessibilityElementsHidden>
        <IconButton label={`${label} earlier`} onPress={dec} disabled={disabled} icon={(col) => <Minus size={ICON_SIZE.row} color={col} strokeWidth={ICON_STROKE} />} />
        <View style={{ minWidth: 48, alignItems: 'center' }}>
          <RollingText
            value={value}
            from={shown.from}
            play={shown.run > 0}
            run={shown.run}
            dir={dir}
            dur="quick"
            stagger={false}
            step
            style={{ ...type.label, ...styles.num }}
            maxScale={maxScale.label}
            color={c.ink}
          />
        </View>
        <IconButton label={`${label} later`} onPress={inc} disabled={disabled} icon={(col) => <Plus size={ICON_SIZE.row} color={col} strokeWidth={ICON_STROKE} />} />
      </View>
    </View>
  );
}


// ── Tab bar label: "Today", with a 4pt dot under the active tab ───────
// The dot means the active tab isn't shown by colour alone (spec §6).
export function TabLabel({ label, focused }: { label: string; focused: boolean }) {
  const { c } = useTheme();
  return (
    <View style={styles.tabLabel} accessibilityShowsLargeContentViewer accessibilityLargeContentTitle={label}>
      <T v="tab" color={focused ? c.ink : c.muted}>{label}</T>
      <View style={[styles.tabDot, { backgroundColor: focused ? c.accent : 'transparent' }]} />
    </View>
  );
}

export function Row({ children, gap = space.md, style }: { children: ReactNode; gap?: number; style?: StyleProp<ViewStyle> }) {
  return <View style={[{ flexDirection: 'row', alignItems: 'center', gap }, style]}>{children}</View>;
}

export function Gap({ h = space.lg }: { h?: number }) {
  return <View style={{ height: h }} />;
}


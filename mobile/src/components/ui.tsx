// ── Screen: safe-area aware page with optional scrolling ──────────────
/**
 * Mobile 1.21: a scrolling Screen lets what is inside it bring one of its own
 * views to the top (the notes page's "On this page" row jumps to a movement).
 * Smooth, or instant under Reduce Motion. null outside a scrolling Screen.
 */
export interface ScreenScroll {
  /** Scroll so `node` sits `offset` pt under the top of the page. */
  scrollToView: (node: View | null, offset?: number) => void;
}
const ScreenScrollContext = createContext<ScreenScroll | null>(null);
export const useScreenScroll = () => useContext(ScreenScrollContext);

export function Screen({
  children,
  scroll = true,
  edges = ['top'],
  onScroll,
  onScrollBeginDrag,
  scrollRef,
}: {
  children: ReactNode;
  scroll?: boolean;
  edges?: ('top' | 'bottom')[];
  /** The scroll view, for a screen that opens at one of its groups (Settings → Badges and plant). */
  scrollRef?: Ref<ScrollView>;
  /** The scroll offset and the visible height (something below the fold waits until it is seen). */
  onScroll?: (y: number, height: number) => void;
  /** The learner starts a new drag (a moment on the screen skips to its end). */
  onScrollBeginDrag?: () => void;
}) {
  const { c } = useTheme();
  const { reduced } = useMotion();
  const [viewH, setViewH] = useState(0);
  const own = useRef<ScrollView | null>(null);
  // The caller's ref when it gives one (an object ref: Settings opens at a group), else our own.
  const ref = (scrollRef && typeof scrollRef === 'object' ? scrollRef : own) as { current: ScrollView | null };
  const scrollApi = useMemo<ScreenScroll>(
    () => ({
      scrollToView: (node, offset = space.sm) => {
        const sv = ref.current as (ScrollView & { getInnerViewRef?: () => unknown; getInnerViewNode?: () => unknown }) | null;
        if (!sv || !node) return;
        const inner = sv.getInnerViewRef?.() ?? sv.getInnerViewNode?.();
        if (!inner) return;
        node.measureLayout(
          inner as View,
          (_x, y) => sv.scrollTo({ y: Math.max(0, y - offset), animated: !reduced }),
          () => {},
        );
      },
    }),
    [reduced, ref],
  );
  const inner = scroll ? (
    <ScrollView
      ref={scrollRef && typeof scrollRef !== 'object' ? scrollRef : ref}
      contentContainerStyle={styles.screenPad}
      keyboardShouldPersistTaps="handled"
      onLayout={onScroll ? (e) => {
        setViewH(e.nativeEvent.layout.height);
        onScroll(0, e.nativeEvent.layout.height);
      } : undefined}
      onScroll={onScroll ? (e) => onScroll(e.nativeEvent.contentOffset.y, viewH || e.nativeEvent.layoutMeasurement.height) : undefined}
      scrollEventThrottle={onScroll ? 32 : undefined}
      onScrollBeginDrag={onScrollBeginDrag}
    >
      <ScreenScrollContext.Provider value={scrollApi}>{children}</ScreenScrollContext.Provider>
    </ScrollView>
  ) : (
    <View style={[styles.screenPad, { flex: 1 }]}>{children}</View>
  );
  return <SafeAreaView edges={edges} style={{ flex: 1, backgroundColor: c.bg }}>{inner}</SafeAreaView>;
}

// ── Text: the Grove v2 type scale ──────────────────────────────────────
// Fraunces (serif) for reading moments and big numbers: number, stat,
// display, hero, stem, quote, stage. Figtree (sans) for everything you
// tap or scan: headline, label, body, small, meta, caption, tab.
export type Variant = TypeVariant;

export function T({
  children,
  v = 'body',
  color,
  style,
  center,
  num,
  accessibilityLabel,
  accessibilityRole,
  maxFontSizeMultiplier,
  numberOfLines,
  selectable,
}: {
  children: ReactNode;
  v?: Variant;
  color?: string;
  style?: StyleProp<TextStyle>;
  center?: boolean;
  /** Tabular figures, so numbers (%, timers, "1 of 3") don't jiggle as they change. */
  num?: boolean;
  accessibilityLabel?: string;
  accessibilityRole?: 'header' | 'text';
  /** Override the spec's per-variant cap (theme/tokens.ts `maxScale`). Never 1.0, except text inside a
   *  fixed-size image (the share card), whose wrapper's accessibilityLabel speaks the full text. */
  maxFontSizeMultiplier?: number;
  numberOfLines?: number;
  /** Lets the learner select and copy the text (an email address, a report to paste). */
  selectable?: boolean;
}) {
  const { c } = useTheme();
  // Meta lines and small captions are secondary text by default.
  const defaultColor = v === 'meta' || v === 'caption' ? c.ink2 : c.ink;
  return (
    <Text
      accessibilityLabel={accessibilityLabel}
      accessibilityRole={accessibilityRole}
      maxFontSizeMultiplier={maxFontSizeMultiplier ?? maxScale[v]}
      numberOfLines={numberOfLines}
      selectable={selectable}
      style={[type[v], { color: color ?? defaultColor }, num && styles.num, center && { textAlign: 'center' }, style]}
    >
      {children}
    </Text>
  );
}

/** A question stem: Fraunces 21/30, stepping down to 20/29 for long stems. */
export function Stem({ children, color, highlight }: { children: string; color?: string; highlight?: string | null }) {
  const { c } = useTheme();
  const { reduced } = useMotion();
  const style = children.length > STEM_LONG_CHARS ? stemLong : undefined;
  // Coach me: mark the LAST capitalised priority word, matched as a whole
  // word (so "MOST" never lights up inside "ALMOST"). Tip colour plus a
  // heavier weight: the weight change is the non-colour cue, and the hint
  // text below also names the word. No underline or background, so it never
  // looks like a link or like an answered (tinted) state.
  const at = highlight ? lastWholeWordIndex(children, highlight) : -1;
  // The wash (mobile 1.8): when Coach me opens, the word's colour washes from
  // ink to the tip colour (200 ms; 120 ms reduced). Colour, not motion. A
  // second, identical copy of the stem sits on top with only the word
  // visible, and fades in; identical text means identical line breaks.
  const wash = useSharedValue(at >= 0 ? 1 : 0);
  useEffect(() => {
    wash.set(at >= 0 ? tween(1, reduced ? 'reduced' : 'reveal') : 0);
  }, [at, reduced, wash]);
  const washStyle = useAnimatedStyle(() => ({ opacity: wash.value }));
  if (!highlight || at < 0) {
    return (
      <T v="stem" color={color} style={style}>
        {children}
      </T>
    );
  }
  const before = children.slice(0, at);
  const after = children.slice(at + highlight.length);
  return (
    <View>
      <T v="stem" color={color} style={style}>
        {before}
        <Text style={{ fontFamily: font.serif500 }}>{highlight}</Text>
        {after}
      </T>
      <Animated.View
        style={[StyleSheet.absoluteFill, styles.noTouch, washStyle]}
        accessible={false}
        accessibilityElementsHidden
        importantForAccessibility="no-hide-descendants"
      >
        <T v="stem" color="transparent" style={style}>
          {before}
          <Text style={{ color: c.tip, fontFamily: font.serif500 }}>{highlight}</Text>
          {after}
        </T>
      </Animated.View>
    </View>
  );
}

// ── Buttons ───────────────────────────────────────────────────────────
export type ButtonKind = 'primary' | 'secondary' | 'ghost' | 'danger' | 'forest';

export function Button({
  label,
  onPress,
  kind = 'primary',
  disabled,
  style,
  icon,
  iconLeading,
  accessibilityHint,
  accessibilityLabel,
  selected,
  expanded,
  ref,
  follow,
}: {
  /** For moving screen-reader focus here (lib/a11y.ts moveFocus). */
  ref?: Ref<View>;
  /** A button that shows or hides something under it (a menu): spoken as expanded / collapsed. */
  expanded?: boolean;
  /** The hero panel's lift: the panel eases a little with the pill (spec §8). */
  follow?: SharedValue<number>;
  label: string;
  onPress: () => void;
  kind?: ButtonKind;
  disabled?: boolean;
  style?: StyleProp<ViewStyle>;
  /** Optional icon, drawn in the label colour: trailing (primary) or leading (forest). */
  icon?: (color: string) => ReactNode;
  iconLeading?: boolean;
  accessibilityHint?: string;
  /** Spoken name when the visible label is a symbol (e.g. "‹"). */
  accessibilityLabel?: string;
  /** For toggle buttons (e.g. Flag): announced as "selected" when on. */
  selected?: boolean;
}) {
  const { c } = useTheme();
  // Each kind = fill · border · label colour (spec §6 "Button").
  // Disabled is its own look (soft + muted), not a faded copy.
  const look = disabled
    ? { bg: c.soft, border: c.soft, fg: c.muted }
    : {
        primary: { bg: c.btn, border: c.btn, fg: c.onBtn },
        secondary: { bg: 'transparent', border: c.control, fg: c.ink },
        ghost: { bg: 'transparent', border: 'transparent', fg: c.accentText },
        danger: { bg: c.wrongBg, border: c.wrongBg, fg: c.wrong },
        forest: { bg: c.pill, border: c.pill, fg: c.onPill },
      }[kind];
  const isForest = kind === 'forest';
  const isGhost = kind === 'ghost';
  // Pressed = a tiny squeeze and dim on the UI thread, not a colour change.
  // A ghost button is text alone, so it only dims (never scale text alone).
  const press = usePressScale({ dim: true, scale: isGhost ? 1 : motion.pressScale, follow });
  return (
    <AnimatedPressable
      ref={ref}
      accessibilityRole="button"
      accessibilityState={{ disabled, selected, ...(expanded === undefined ? {} : { expanded }) }}
      accessibilityHint={accessibilityHint}
      accessibilityLabel={accessibilityLabel ?? label}
      onPress={onPress}
      disabled={disabled}
      onPressIn={press.onPressIn}
      onPressOut={press.onPressOut}
      style={[
        isForest ? styles.buttonForest : isGhost ? styles.buttonGhost : styles.button,
        { backgroundColor: look.bg, borderColor: look.border },
        style,
        press.style,
      ]}
    >
      {iconLeading && icon?.(look.fg)}
      <Text maxFontSizeMultiplier={maxScale.label} style={[isForest || isGhost ? type.label : styles.buttonLabel, { color: look.fg, flexShrink: 1, textAlign: 'center' }]}>
        {label}
      </Text>
      {!iconLeading && icon?.(look.fg)}
    </AnimatedPressable>
  );
}

// ── Card: a surface ───────────────────────────────────────────────────
// raised (L2) = white card with `cardShadow` (dark: 1.5px outline) for things
// you choose between; plate (L1) = a quiet tonal panel for figures, grids and
// offers, never a choice; plain = no box at all; forest = the one brand panel.
export function Card({
  children,
  style,
  onPress,
  emphasis,
  variant = 'raised',
  accessibilityLabel,
}: {
  children: ReactNode;
  style?: StyleProp<ViewStyle>;
  onPress?: () => void;
  /** A 1.5px brand-green outline: "this matters most right now". */
  emphasis?: boolean;
  variant?: 'raised' | 'plate' | 'plain' | 'forest';
  accessibilityLabel?: string;
}) {
  const { c, isDark } = useTheme();
  const look =
    variant === 'forest'
      ? [styles.forest, { backgroundColor: c.forest, borderTopColor: forestHighlight[isDark ? 'dark' : 'light'] }]
      : variant === 'plain'
        ? null
        : variant === 'plate'
          ? [styles.plate, { backgroundColor: c.raised2 }]
          : [
              styles.card,
              { backgroundColor: c.raised, borderColor: emphasis ? c.accent : isDark ? c.line : 'transparent' },
              !isDark && styles.cardLift,
            ];
  const base = [look, style];
  // A static card has no press feedback, so it builds no animated styles (long lists on low-end Android).
  if (!onPress) return <View style={base}>{children}</View>;
  return (
    <PressCard style={base} onPress={onPress} accessibilityLabel={accessibilityLabel}>
      {children}
    </PressCard>
  );
}

function PressCard({ style, onPress, accessibilityLabel, children }: { style: StyleProp<ViewStyle>; onPress: () => void; accessibilityLabel?: string; children: ReactNode }) {
  const press = usePressScale();
  return (
    <AnimatedPressable
      accessibilityRole="button"
      accessibilityLabel={accessibilityLabel}
      onPress={onPress}
      onPressIn={press.onPressIn}
      onPressOut={press.onPressOut}
      style={[style, press.style]}
    >
      {children}
    </AnimatedPressable>
  );
}

// ── HeroPanel: the forest panel with botanical line art (spec §6) ─────
export function HeroPanel({
  caption,
  captionLead,
  captionExtra,
  captionMeta,
  captionMetaLabel,
  title,
  meta,
  action,
  art = 'frond',
  sway = true,
  breathe = false,
  children,
  style,
  titleLabel,
  metaLabel,
  wideTitle,
  wideMeta,
  captionLabel,
}: {
  caption?: string;
  /** Before the caption on the same line (e.g. a domain dot). */
  captionLead?: ReactNode;
  /** After the caption on the same line (e.g. plan leaf marks). */
  captionExtra?: ReactNode;
  /** One meta line under the caption row (Today, mobile 1.15: "About 20 min today"). */
  captionMeta?: string;
  /** Spoken caption meta, when it differs ("About 20 minutes today" for "About 20 min today"). */
  captionMetaLabel?: string;
  title: string;
  meta?: string;
  action?: { label: string; onPress: () => void; icon?: (color: string) => ReactNode; hint?: string };
  art?: BotanyKind;
  /** Gentle frond sway while the screen is focused (off under Reduce Motion). */
  sway?: boolean;
  /** One slow breath of the art, once, when this turns true (the Exam-ready moment; off under Reduce Motion). */
  breathe?: boolean;
  /** Extra content under the title (e.g. the clearing card's stats). */
  children?: ReactNode;
  style?: StyleProp<ViewStyle>;
  /** Spoken title, when it differs from the visible one. */
  titleLabel?: string;
  /** Spoken meta line, when it differs from the visible one (e.g. "62% now, aiming for 70%" for "62% → 70%"). */
  metaLabel?: string;
  /** Let a short title use the full width (art there is low and sparse). */
  wideTitle?: boolean;
  /** Let only the meta line run full width (one line over the low, faint art; mobile 1.21, Learn). */
  wideMeta?: boolean;
  /** Spoken caption, when it differs ("Start here, about 19 minutes" for "Start here · about 19 min"). */
  captionLabel?: string;
}) {
  const { c } = useTheme();
  const { reduced } = useMotion();
  const large = useFontScale() >= LARGE_TEXT;
  // The lift (spec §8): while the pill is pressed the panel eases to .99, so
  // the whole task seems to rise toward you. Static under Reduce Motion.
  const lift = useSharedValue(0);
  const liftStyle = useAnimatedStyle(() => ({ transform: [{ scale: reduced ? 1 : 1 - 0.01 * lift.value }] }));
  return (
    <Animated.View style={[style, liftStyle]}>
    <Card variant="forest">
      {/* Two layers, so the text can never disappear behind the art (the
          Android "empty green block" on Play):
          1. ART: its own absolutely-filled layer that does the rounded
             clipping, with the drawing in a box of EXPLICIT size. The panel
             itself no longer clips, so the title and button never share a
             clipping parent with a rotating (swaying) SVG.
          2. CONTENT: zIndex 1, always drawn above the art on every platform.
          Decorative art bleeds off the top-right; screen readers skip it. */}
      <View
        testID="hero-art"
        style={[StyleSheet.absoluteFill, styles.heroArtClip, styles.noTouch]}
        accessible={false}
        importantForAccessibility="no-hide-descendants"
      >
        {/* Depth: the panel is lit from the top, a vertical gradient from
            `forestTop` down to `forest`, with the 1px highlight above it (dark
            since mobile 1.9, light since 1.21). */}
        {c.forestTop !== c.forest && <ForestLight top={c.forestTop} bottom={c.forest} />}
        <View style={[styles.heroArt, botanySize(art)]}>
          <Botany kind={art} color={c.forestLine} sway={sway} breathe={breathe} />
        </View>
      </View>
      <View testID="hero-content" style={styles.heroContent}>
        {caption && (
          <Row gap={space.sm} style={{ flexWrap: 'wrap' }}>
            {captionLead ? (
              // A lead (a domain dot, a game glyph) stays on its caption's line: at large text
              // the caption wraps BESIDE it (never the lead alone on a line). With nothing after
              // it, the pair keeps clear of the art like the title (full width at large text).
              <Row gap={space.sm} style={{ flexShrink: 1, maxWidth: !captionExtra && !large && !wideTitle ? 250 : '100%' }}>
                {captionLead}
                <T v="caption" color={c.onForest2} accessibilityLabel={captionLabel} style={{ flexShrink: 1 }}>{caption}</T>
              </Row>
            ) : (
              <T v="caption" color={c.onForest2} accessibilityLabel={captionLabel}>{caption}</T>
            )}
            {captionExtra}
          </Row>
        )}
        {captionMeta ? (
          <T v="meta" color={c.onForest2} accessibilityLabel={captionMetaLabel} style={{ marginTop: space.xs }}>
            {captionMeta}
          </T>
        ) : null}
        {/* While the title fits in 2 lines it stays clear of the art (maxWidth 250);
            longer titles, or large text, run full width over the low-contrast art. */}
        <T
          v="hero"
          color={c.onForest}
          accessibilityRole="header"
          accessibilityLabel={titleLabel}
          style={{ marginTop: caption ? space.sm : 0, maxWidth: title.length <= 34 && !large && !wideTitle ? 250 : undefined }}
        >
          {title}
        </T>
        {/* The meta line keeps clear of the art too (it wraps instead), except
            with wideTitle or large text, where it runs full width like the title. */}
        {meta && (
          <T v="meta" color={c.onForest2} accessibilityLabel={metaLabel} style={{ marginTop: space.xs, maxWidth: !large && !wideTitle && !wideMeta ? 250 : undefined }}>
            {meta}
          </T>
        )}
        {children}
        {action && (
          <Button
            kind="forest"
            label={action.label}
            onPress={action.onPress}
            accessibilityHint={action.hint}
            icon={action.icon}
            iconLeading
            follow={lift}
            style={{ marginTop: space.gutter, alignSelf: 'flex-start' }}
          />
        )}
      </View>
    </Card>
    </Animated.View>
  );
}


// ── Segmented control (spec §11 "Practice") ───────────────────────────
// `soft` track, the selected segment `raised` (+ soft shadow in light mode).
// Numeral options show a Fraunces 20 numeral + a small unit. Stacks into a
// column at large text sizes instead of squeezing.
/** Dark-mode fill for the selected segment (DESIGN_SYSTEM.md, Practice screen). */
const SEG_ON_DARK = '#2C372F';
/** 44pt segment + 2pt each side = 48pt to the finger (the 3pt track gap keeps neighbours apart). */
export const SEG_HIT_SLOP = 2;
/** `raisedShadow` without Android's `elevation`, for a layer drawn beneath its own content. */
const { elevation: _elevation, ...layerShadow } = raisedShadow;

export function Segmented<V extends string | number>({
  options,
  value,
  onChange,
  accessibilityLabel,
}: {
  options: { value: V; label: string; numeral?: string; icon?: (color: string) => ReactNode; spoken?: string }[];
  /** null = nothing chosen yet (e.g. Forecast before each answer). */
  value: V | null;
  onChange: (v: V) => void;
  accessibilityLabel: string;
}) {
  const { c, isDark } = useTheme();
  const { reduced } = useMotion();
  const stacked = useFontScale() >= LARGE_TEXT;
  // The thumb (spec §8): ONE selected shape that slides to the new choice
  // (translateX, a settle spring with no visible overshoot). It needs the
  // track's width, so until the first layout, and in a stacked column at
  // large text or under Reduce Motion, each segment cross-fades its own
  // selected look in place instead. Both look exactly the same at rest.
  const [trackW, setTrackW] = useState(0);
  const n = options.length;
  const at = options.findIndex((o) => o.value === value);
  const itemW = trackW > 0 ? (trackW - SEG_INSET * 2 - SEG_GAP * (n - 1)) / n : 0;
  const slide = !stacked && !reduced && itemW > 0;
  // The thumb's place in SEGMENTS, not points: its offset is drawn from the
  // current width, so the first layout (and a rotation) puts it in place at
  // once. It only ever moves because the learner chose something.
  const pos = useSharedValue(Math.max(at, 0));
  const shown = useSharedValue(at >= 0 ? 1 : 0);
  const lastAt = useRef(at);
  useEffect(() => {
    const from = lastAt.current;
    lastAt.current = at;
    if (!slide || from === at) {
      // Not sliding, or only the size or mode changed: be in place.
      pos.set(Math.max(at, 0));
      shown.set(at >= 0 ? 1 : 0);
      return;
    }
    if (at < 0) {
      shown.set(tween(0, 'quick'));
    } else if (from < 0) {
      // The first choice appears in place: there is nowhere to slide from.
      pos.set(at);
      shown.set(tween(1, 'select'));
    } else {
      pos.set(withSpring(at, { ...motion.spring.settle, reduceMotion: ReduceMotion.Never }));
    }
  }, [at, slide, pos, shown]);
  const step = itemW + SEG_GAP;
  const thumbStyle = useAnimatedStyle(() => ({ opacity: shown.value, transform: [{ translateX: pos.value * step }] }));
  // Selected = ink (spec §5): a 1.5px ink outline makes the choice clear in
  // both modes (fill alone was ~1.1:1, failing WCAG 1.4.11). Fill: `raised`
  // + shadow in light, the spec's lifted #2C372F in dark. The thumb and the
  // per-segment layer sit UNDER the labels, so they never take Android
  // `elevation` (it would lift them above the label they belong to): the
  // shadow is iOS and web only, and the ink outline carries the choice.
  const onLook = [{ backgroundColor: isDark ? SEG_ON_DARK : c.raised, borderWidth: 1.5, borderColor: c.ink, borderRadius: 22 }, !isDark && layerShadow];
  return (
    <View
      accessibilityRole="radiogroup"
      accessibilityLabel={accessibilityLabel}
      onLayout={(e) => setTrackW(e.nativeEvent.layout.width)}
      style={[styles.seg2, { backgroundColor: c.soft, flexDirection: stacked ? 'column' : 'row' }]}
    >
      {slide && (
        <Animated.View
          accessible={false}
          importantForAccessibility="no"
          style={[styles.noTouch, styles.segThumb, { width: itemW }, onLook, thumbStyle]}
        />
      )}
      {options.map((o) => {
        const on = o.value === value;
        return (
          <Pressable
            key={String(o.value)}
            accessibilityRole="radio"
            accessibilityState={{ checked: on }}
            accessibilityLabel={o.spoken ?? (o.numeral ? `${o.numeral} ${o.label}` : o.label)}
            onPress={() => onChange(o.value)}
            hitSlop={SEG_HIT_SLOP}
            // A transparent border of the same width as the selected one, so nothing jumps.
            style={[styles.segItem, !stacked && { flex: 1 }, { borderWidth: 1.5, borderColor: 'transparent' }]}
          >
            {!slide && <StateLayer on={on} style={[styles.segOn, onLook]} />}
            {o.icon ? <View>{o.icon(on ? c.ink : c.ink2)}</View> : null}
            {o.numeral ? (
              <>
                <BigNum value={o.numeral} size={20} />
                <Unit color={on ? c.ink : c.ink2}>{o.label}</Unit>
              </>
            ) : (
              <T v="caption" color={on ? c.ink : c.ink2}>{o.label}</T>
            )}
          </Pressable>
        );
      })}
    </View>
  );
}

// ── ChipRow: one scrolling line of chips with a fade at the right edge ─
// At large text sizes the chips wrap instead of scrolling (spec §10.7).
export function ChipRow({ children }: { children: ReactNode }) {
  const { c } = useTheme();
  const wrap = useFontScale() >= LARGE_TEXT;
  if (wrap) return <View style={styles.chipWrap}>{children}</View>;
  return (
    <View style={{ marginRight: -space.gutter }}>
      <ScrollView horizontal showsHorizontalScrollIndicator={false} contentContainerStyle={styles.chipScroll}>
        {children}
      </ScrollView>
      {/* Right-edge fade hints that the row scrolls. */}
      <Svg width={56} height="100%" style={[styles.chipFade, styles.noTouch]}>
        <Defs>
          <LinearGradient id="chipFade" x1="0" y1="0" x2="1" y2="0">
            <Stop offset="0" stopColor={c.bg} stopOpacity={0} />
            <Stop offset="1" stopColor={c.bg} stopOpacity={1} />
          </LinearGradient>
        </Defs>
        <Rect x="0" y="0" width="56" height="100%" fill="url(#chipFade)" />
      </Svg>
    </View>
  );
}

/**
 * Input focus (mobile 1.21, spec §6 "Inputs"): idle = a 1.5 `control` outline
 * in BOTH themes (dark `line` was 1.24:1, failing WCAG 1.4.11); focused = the
 * same outline in `ink`, the app's "selected" colour (no layout shift). On the
 * web the browser's own focus ring is turned off, so it never draws a square
 * box inside the rounded field.
 */
const NO_WEB_OUTLINE: TextStyle | null = Platform.OS === 'web' ? { outlineWidth: 0 } : null;

// ── SearchField: a rounded text box for searching (Learn, Study notes) ─
// A leading search glyph (20, muted) says what the box is for. Body type, so
// typed text grows with the phone's text size (×2 cap). 48pt tall minimum;
// a ✕ button (48pt) clears it when there is text.
export function SearchField({
  value,
  onChangeText,
  placeholder,
  accessibilityLabel,
  accessibilityHint,
}: {
  value: string;
  onChangeText: (v: string) => void;
  placeholder: string;
  accessibilityLabel: string;
  accessibilityHint?: string;
}) {
  const { c } = useTheme();
  const [focused, setFocused] = useState(false);
  return (
    <View style={[styles.search, { backgroundColor: c.raised, borderColor: focused ? c.ink : c.control }]}>
      <View accessible={false} importantForAccessibility="no-hide-descendants" accessibilityElementsHidden style={styles.searchGlyph}>
        <Search size={ICON_SIZE.row} color={c.muted} strokeWidth={ICON_STROKE} />
      </View>
      <TextInput
        value={value}
        onChangeText={onChangeText}
        onFocus={() => setFocused(true)}
        onBlur={() => setFocused(false)}
        placeholder={placeholder}
        placeholderTextColor={c.muted}
        accessibilityLabel={accessibilityLabel}
        accessibilityHint={accessibilityHint}
        maxFontSizeMultiplier={maxScale.body}
        autoCorrect={false}
        autoCapitalize="none"
        returnKeyType="search"
        clearButtonMode="never"
        style={[type.body, { flex: 1, color: c.ink, paddingVertical: space.md }, NO_WEB_OUTLINE]}
      />
      {value.length > 0 && (
        <Pressable
          accessibilityRole="button"
          accessibilityLabel="Clear search"
          onPress={() => onChangeText('')}
          style={styles.searchClear}
        >
          <X size={ICON_SIZE.row} color={c.ink2} strokeWidth={ICON_STROKE} />
        </Pressable>
      )}
    </View>
  );
}

// ── NoteField: a few lines of the learner's own words (Report a problem) ──
// Same look as SearchField (raised, 1.5 outline, radius 16, body text that
// grows with the phone's text size, ×2 cap), but multi-line, with a quiet
// character count under it. The visible caption above it is its name.
// The outline is `control` in BOTH themes (UX review P4): dark `line` was
// 1.24:1 on the fill, so the field's edges vanished once the placeholder
// was gone (WCAG 1.4.11 asks 3:1; `control` is 3.31 dark, 3.65 light).
// Reaching the limit is announced once, so it is never silent (UX O6).
export function NoteField({
  value,
  onChangeText,
  placeholder,
  accessibilityLabel,
  maxLength,
  ref,
}: {
  value: string;
  onChangeText: (v: string) => void;
  placeholder: string;
  accessibilityLabel: string;
  maxLength: number;
  /** To focus the field (the board composer's "Edit my post"). */
  ref?: Ref<TextInput>;
}) {
  const { c } = useTheme();
  const [focused, setFocused] = useState(false);
  const change = (next: string) => {
    if (next.length >= maxLength && value.length < maxLength) sayLater(`That’s the limit, ${maxLength} characters.`);
    onChangeText(next);
  };
  return (
    <View>
      <TextInput
        ref={ref}
        value={value}
        onChangeText={change}
        onFocus={() => setFocused(true)}
        onBlur={() => setFocused(false)}
        placeholder={placeholder}
        placeholderTextColor={c.muted}
        accessibilityLabel={accessibilityLabel}
        accessibilityHint={`Optional. Up to ${maxLength} characters.`}
        maxFontSizeMultiplier={maxScale.body}
        maxLength={maxLength}
        multiline
        textAlignVertical="top"
        style={[
          type.body,
          styles.note,
          { color: c.ink, backgroundColor: c.raised, borderColor: focused ? c.ink : c.control },
          NO_WEB_OUTLINE,
        ]}
      />
      <T v="meta" num style={{ textAlign: 'right', marginTop: space.xs }} accessibilityLabel={`${value.length} of ${maxLength} characters`}>
        {`${value.length} / ${maxLength}`}
      </T>
    </View>
  );
}

/** A visible line the field itself already speaks (its name or hint): hidden from screen readers on iOS and Android. */
const SPOKEN_BY_FIELD = { accessibilityElementsHidden: true, importantForAccessibility: 'no-hide-descendants' } as const;

// ── TextField: one line the learner types (sign-in email, code, DELETE) ──
// Uplift Phase 6 (accounts, built OFF). The same look as NoteField (raised,
// 1.5 `control` outline in both themes, radius 16, body text that grows with
// the phone's text size up to ×2), one line, at least 56pt tall. Its visible
// `label` sits above it and is also its spoken name. A problem shows under
// it in `tip` (Grove keeps red for wrong answers), with the outline in `tip`
// too, is part of the spoken hint, and is announced once when it appears.
// The visible label, help and problem lines are hidden from screen readers:
// the field already says them (name and hint), so they are never read twice.
// `tabular` lines digits up (the 6-digit code).
export function TextField({
  label,
  value,
  onChangeText,
  problem,
  help,
  ref,
  tabular,
  ...input
}: {
  label: string;
  value: string;
  onChangeText: (v: string) => void;
  /** Why the value can't be used yet ("Enter an email address like …"). */
  problem?: string | null;
  /** A quiet line under the field when there is no problem. */
  help?: string;
  ref?: Ref<TextInput>;
  tabular?: boolean;
} & Pick<
  ComponentProps<typeof TextInput>,
  'keyboardType' | 'autoComplete' | 'textContentType' | 'autoCapitalize' | 'maxLength' | 'onSubmitEditing' | 'returnKeyType' | 'editable' | 'placeholder' | 'autoFocus'
>) {
  const { c } = useTheme();
  const [focused, setFocused] = useState(false);
  const said = useRef<string | null>(null);
  useEffect(() => {
    if (problem && problem !== said.current) sayLater(problem);
    said.current = problem ?? null;
  }, [problem]);
  return (
    <View style={{ marginTop: space.md }}>
      <View {...SPOKEN_BY_FIELD}>
        <T v="label">{label}</T>
      </View>
      <TextInput
        ref={ref}
        value={value}
        onChangeText={onChangeText}
        placeholderTextColor={c.muted}
        accessibilityLabel={label}
        accessibilityHint={problem ?? help}
        maxFontSizeMultiplier={maxScale.body}
        autoCorrect={false}
        {...input}
        onFocus={() => setFocused(true)}
        onBlur={() => setFocused(false)}
        style={[
          type.body,
          tabular ? { fontVariant: ['tabular-nums'] } : null,
          styles.field,
          // A problem keeps its `tip` outline while focused (the problem is what matters).
          { color: c.ink, backgroundColor: c.raised, borderColor: problem ? c.tip : focused ? c.ink : c.control },
          NO_WEB_OUTLINE,
        ]}
      />
      {problem ? (
        <View {...SPOKEN_BY_FIELD}>
          <T v="meta" color={c.tip} style={{ marginTop: space.xs }}>{problem}</T>
        </View>
      ) : help ? (
        <View {...SPOKEN_BY_FIELD}>
          <T v="meta" style={{ marginTop: space.xs }}>{help}</T>
        </View>
      ) : null}
    </View>
  );
}


#!/usr/bin/env python3
"""Build the CIA Challenge Exam question pack (data/cia/ciac/) from tagged Part items.

The Challenge Exam's 40 topics are 40 of the three Parts' 62 topics, word for
word (docs/content/CIA_CHALLENGE_MAP.md). So no Challenge question is written
by hand: every item is written once, in its Part's file, and carries
`challenge_ref` (the Challenge topic it serves, such as "C1"). This script
copies each tagged item into data/cia/ciac/originals/d{1..5}.json under a
Challenge id.

NEVER EDIT data/cia/ciac/originals/ OR data/cia/ciac/id_map.json BY HAND.
Fix the source item in its Part file and run this script again.

Ids never move. data/cia/ciac/id_map.json is append-only: a source id is given
the next free number in its Challenge section the first time it is seen and
keeps it for good, because a learner's saved progress is keyed by question id.
A source item that is deleted, loses its tag or moves to another Challenge
section is marked "retired" (its number is never reused); a moved item gets a
new id.

What changes in a copied item: `id` (ciac_d3_001), `domain` (the Challenge
section number) and the code and title at the start of `subtopic` (2A1 becomes
4C1; "4" marks the fourth exam). Everything else, the answer included, is the
source item's.

Items that rest on a Topical Requirement that is not testable yet keep their
`testable_from` date; mock and free-sample builders leave them out until then.

Usage:
  python3 data/cia/tools/build_challenge.py          # rebuild ciac/originals and the id map
  python3 data/cia/tools/build_challenge.py --check  # fail if the files on disk differ from a rebuild
"""
import sys

import cia_common as c


def build(root, today):
    outline = c.load_outline(root)
    ch = c.challenge_topics(outline)
    topics = c.part_topics(outline)
    map_path = root / c.CHALLENGE / "id_map.json"
    id_map = c.read_json(map_path) if map_path.exists() else {"schema_version": 1, "note":
             "Append-only. Source Part item id to Challenge id. Never edit by hand; never reuse a number.", "map": []}
    entries = [dict(e) for e in id_map["map"]]
    problems = []
    tagged = {}
    for _pack, _d, q in c.all_items(root):
        ref = q.get("challenge_ref")
        if ref:
            if ref not in ch:
                problems.append(f"{q['id']}: challenge_ref '{ref}' is not a Challenge topic")
            else:
                tagged[q["id"]] = q
    active = {e["source"]: e for e in entries if e["status"] == "active"}
    used = {}
    for e in entries:
        d, n = int(e["id"].split("_")[1][1:]), int(e["id"].split("_")[2])
        used[d] = max(used.get(d, 0), n)
    for e in entries:                      # retire what is gone or has moved section
        if e["status"] != "active":
            continue
        q = tagged.get(e["source"])
        if q is None or ch[q["challenge_ref"]]["domain"] != int(e["id"].split("_")[1][1:]):
            e["status"] = "retired"
            active.pop(e["source"], None)
    for sid in sorted(tagged):             # append new sources, in id order
        if sid not in active:
            d = ch[tagged[sid]["challenge_ref"]]["domain"]
            used[d] = used.get(d, 0) + 1
            e = {"source": sid, "id": f"{c.CHALLENGE}_d{d}_{used[d]:03d}", "status": "active"}
            entries.append(e)
            active[sid] = e
    files = {}
    sections = c.exam(outline, c.CHALLENGE)["sections"]
    for s in sections:
        rows = []
        for e in sorted((e for e in active.values() if int(e["id"].split("_")[1][1:]) == s["domain"]),
                        key=lambda e: e["id"]):
            q = dict(tagged[e["source"]])
            t = ch[q["challenge_ref"]]
            label = q["subtopic"].split(". ", 1)[1] if ". " in q["subtopic"] else q["subtopic"]
            q["id"], q["domain"] = e["id"], s["domain"]
            q["subtopic"] = f"{t['code']} {topics[t['part_code']]['title']}. {label}"
            rows.append(q)
        files[s["domain"]] = {
            "_meta": {"comment": "GENERATED by data/cia/tools/build_challenge.py from the tagged items in "
                      "data/cia/cia1, cia2 and cia3. Do not edit: fix the source item and rebuild. "
                      "Source ids: data/cia/ciac/id_map.json. Original KaiSip questions; not affiliated "
                      "with or endorsed by The IIA.", "schema_version": 1},
            "domain": s["domain"], "domain_name": s["name"], "weight": f"{s['weight']}%", "questions": rows}
    id_map = dict(id_map, map=entries)
    return files, id_map, sections, problems, today


def report(files, sections, today, questions):
    live = {d: [q for q in f["questions"] if not c.not_yet_testable(q, today)] for d, f in files.items()}
    need = {s["domain"]: questions * s["weight"] / 100 for s in sections}
    forms = min((len(live[d]) / need[d] for d in need), default=0)
    print("ciac: " + " · ".join(f"{s['letter']} {len(files[s['domain']]['questions'])} ({s['weight']}%)" for s in sections)
          + f" · testable today {sum(len(v) for v in live.values())}"
          + f" · full {questions}-question mocks without repeats: {int(forms)}")


def main(argv):
    root, today, args = c.setup(argv)
    files, id_map, sections, problems, today = build(root, today)
    for p in problems:
        print(f"ERROR {p}")
    out = root / c.CHALLENGE
    targets = {out / "originals" / f"d{d}.json": c.dump_json(f) for d, f in files.items()}
    targets[out / "id_map.json"] = c.dump_json(id_map)
    total = sum(len(f["questions"]) for f in files.values())
    if "--check" in args:
        stale = [p for p, text in targets.items()
                 if (p.read_text(encoding="utf-8") if p.exists() else None) != text
                 and (p.exists() or total or id_map["map"])]   # nothing tagged yet and nothing on disk is fine
        for p in stale:
            print(f"ERROR {p.relative_to(root)} is not what build_challenge.py produces "
                  "(hand-edited, or a source item changed): run python3 data/cia/tools/build_challenge.py")
        report(files, sections, today, c.exam(c.load_outline(root), c.CHALLENGE)["questions"])
        print(f"build_challenge --check: {len(stale)} file(s) out of date, {len(problems)} problem(s)")
        return 1 if stale or problems else 0
    if problems:
        return 1
    if total or id_map["map"]:
        for p, text in targets.items():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
    report(files, sections, today, c.exam(c.load_outline(root), c.CHALLENGE)["questions"])
    print(f"build_challenge: {total} item(s) written, {sum(1 for e in id_map['map'] if e['status'] == 'retired')} retired id(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
